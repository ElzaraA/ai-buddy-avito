"""
dataset_split.py — Leakage-free train/val/test split for RecSys.

Strategy
--------
We have (intern_id, task_id, label) interactions generated by a synthetic
function. Two leakage risks:

  1. The feature extractor computed `prior_pos`/`prior_neg` over ALL
     interactions of an intern, including the current row. This means the
     model could "see" the current row's label indirectly via the prior
     counts, giving artificially inflated metrics.

  2. Random shuffling of 6000 rows still leaks: many intern-task pairs
     appear multiple times (the generator picks a random pair each time),
     so a (intern, task) can appear in both train and test. That violates
     the assumption of a held-out test set.

Both problems are fixed here.

We expose two split strategies:

  - `random_split`: random 70/15/15 split. Some (intern, task) pairs may
    appear in multiple splits. Used only for sanity / debugging.

  - `intern_split`: holds out a fixed fraction of INTERNS (and ALL of
    their interactions) for val and test. This measures "cold-start on a
    new intern" — relevant for RecSys evaluation.

  - `leak_free_split`: random split over UNIQUE (intern, task) pairs,
    then ALL interactions of each unique pair go into the same split.
    This is the default and matches the assumption "the system has not
    observed this (user, item) interaction before."

The default `make_default_split` uses `leak_free_split` with a fixed seed.

Each split exposes: train_rows, val_rows, test_rows, prior_counts.
`prior_counts` is a dict keyed by intern_id -> (pos, neg) counting only
TRAIN interactions. This is what feature extraction should use.
"""

from __future__ import annotations

import random
from dataclasses import dataclass
from typing import Iterable


@dataclass(frozen=True)
class Row:
    intern_id: str
    task_id: str
    label: int


@dataclass
class Split:
    train: list[Row]
    val: list[Row]
    test: list[Row]
    prior_counts: dict[str, tuple[int, int]]  # intern_id -> (pos, neg) over TRAIN only

    def stats(self) -> dict:
        def s(rows: list[Row]) -> dict:
            n = len(rows)
            pos = sum(r.label for r in rows)
            pairs = {r.intern_id: set() for r in rows}
            for r in rows:
                pass
            unique_pairs = len({(r.intern_id, r.task_id) for r in rows})
            unique_interns = len({r.intern_id for r in rows})
            return {
                "n": n,
                "pos": pos,
                "pos_rate": pos / n if n else 0.0,
                "unique_pairs": unique_pairs,
                "unique_interns": unique_interns,
            }
        return {
            "train": s(self.train),
            "val":   s(self.val),
            "test":  s(self.test),
            "prior_interns": len(self.prior_counts),
        }


def load_rows_from_dataset(dataset_path) -> list[Row]:
    """Load (intern_id, task_id, label) rows from ml/recsys/artifacts/dataset.json."""
    import json
    from pathlib import Path

    p = Path(dataset_path)
    data = json.loads(p.read_text(encoding="utf-8"))
    rows = [
        Row(intern_id=x["intern_id"], task_id=x["task_id"], label=int(x["label"]))
        for x in data["interactions"]
    ]
    return rows


def leak_free_split(
    rows: list[Row], val_ratio: float = 0.15, test_ratio: float = 0.15, seed: int = 42
) -> Split:
    """Split interactions so that no (intern_id, task_id) pair appears in
    more than one split. Prior counts are computed on TRAIN only.
    """
    rng = random.Random(seed)
    by_pair: dict[tuple[str, str], list[Row]] = {}
    for r in rows:
        by_pair.setdefault((r.intern_id, r.task_id), []).append(r)

    pairs = list(by_pair.keys())
    rng.shuffle(pairs)

    n = len(pairs)
    n_test = int(n * test_ratio)
    n_val = int(n * val_ratio)
    test_pairs = set(pairs[:n_test])
    val_pairs = set(pairs[n_test : n_test + n_val])
    train_pairs = set(pairs[n_test + n_val :])

    train = [r for p in train_pairs for r in by_pair[p]]
    val = [r for p in val_pairs for r in by_pair[p]]
    test = [r for p in test_pairs for r in by_pair[p]]

    prior: dict[str, list[int]] = {}
    for r in train:
        prior.setdefault(r.intern_id, [0, 0])[r.label] += 1
    prior_counts = {i: tuple(v) for i, v in prior.items()}

    rng.shuffle(train)
    rng.shuffle(val)
    rng.shuffle(test)

    return Split(train=train, val=val, test=test, prior_counts=prior_counts)


def intern_split(
    rows: list[Row], val_ratio: float = 0.15, test_ratio: float = 0.15, seed: int = 42
) -> Split:
    """Hold out a fraction of INTERNS (and ALL their interactions) for val/test."""
    rng = random.Random(seed)
    interns = sorted({r.intern_id for r in rows})
    rng.shuffle(interns)
    n = len(interns)
    n_test = int(n * test_ratio)
    n_val = int(n * val_ratio)
    test_interns = set(interns[:n_test])
    val_interns = set(interns[n_test : n_test + n_val])
    train_interns = set(interns[n_test + n_val :])

    train = [r for r in rows if r.intern_id in train_interns]
    val = [r for r in rows if r.intern_id in val_interns]
    test = [r for r in rows if r.intern_id in test_interns]

    prior: dict[str, list[int]] = {}
    for r in train:
        prior.setdefault(r.intern_id, [0, 0])[r.label] += 1
    prior_counts = {i: tuple(v) for i, v in prior.items()}

    return Split(train=train, val=val, test=test, prior_counts=prior_counts)


def make_default_split(dataset_path) -> Split:
    return leak_free_split(load_rows_from_dataset(dataset_path), seed=42)


__all__ = [
    "Row",
    "Split",
    "load_rows_from_dataset",
    "leak_free_split",
    "intern_split",
    "make_default_split",
]

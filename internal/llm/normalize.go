package llm

import (
	"strings"
	"unicode"
)

// Normalize приводит реплику стажёра к форме, которую понимают правила маршрутизации:
// нижний регистр, «ё» → «е», разговорные и сокращённые формы → полные слова
// («чё» → «что», «пн» → «понедельник», «зп» → «зарплата»), «пж»/«плиз» убираются.
// Заменяются только целые слова: «что» внутри «чтобы» не трогаем, числа и знаки сохраняются.
func Normalize(s string) string {
	s = strings.ReplaceAll(strings.ToLower(s), "ё", "е")
	var b strings.Builder
	rs := []rune(s)
	for i := 0; i < len(rs); {
		if !unicode.IsLetter(rs[i]) {
			b.WriteRune(rs[i])
			i++
			continue
		}
		j := i
		for j < len(rs) && unicode.IsLetter(rs[j]) {
			j++
		}
		w := string(rs[i:j])
		if r, ok := wordFixes[w]; ok {
			w = r
		}
		b.WriteString(w)
		i = j
	}
	out := b.String()
	for _, p := range phraseFixes {
		out = strings.ReplaceAll(out, p[0], p[1])
	}
	return out
}

